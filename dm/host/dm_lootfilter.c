// 掉落过滤（用原版自带的战利品过滤器，不自造一套）：缺省用外部导入的「檬3c屏蔽」（Meng3c，任何难度都生效），
// 也可以在 <存档>/Settings/dm-lootfilter.txt 里改成按难度（profile=auto）或固定某一档（lite / std / strict）。
// 原版的机制（Switch 版主程序里完整存在，只是暂停菜单里的入口被我们的布局藏着）：
//   · 规则文件 <存档>/Settings/<配置名>.fltr 在启动时全部载入；<存档>/Settings/lootfilter.json 的 Profiles 段记「角色名 → 配置名」，
//     每次进局收到自己的玩家单位时重读一次这个文件、按角色名选当前配置（main+0x464130 → 0x382280 → 0x381d10）。
//   · 判定 main+0x37f3d4(过滤器 main+0x2d58520, 物品) 返回 1 可见 / 0 隐藏，全映像只有三处调用：地上名字标签两处（不建标签）、
//     手柄每帧选目标一处（主钮不去捡）。只在术士君临模式生效（函数开头的模式门）。任一「显示」规则命中即可见，否则有「隐藏」规则命中才藏。
//   · 一条规则里：非装备看 itemCategory（界面类别名，父类 misc 含全部子类）或 itemCode（物品三字码）；装备看 equipmentRarity（稀有度）、
//     equipmentQuality（普通 / 扩展 / 精英档，只对分档的类别有效——戒指项链护身符珠宝头环不分档）、equipmentCategory / equipmentItemCode。
//     投掷药水算装备（武器），要用 equipmentItemCode 点名（实测：写在 itemCode 里藏不住）。
// 本文件的做法：规则内容不再在这里拼字符串，改成 fltr.py 生成好的 JSON（dm_lootfilter_data.h 内嵌），挂存档时整份写进 Settings/。
// 一共 7 份：作者原样导入的「檬3c屏蔽」（Meng3c，7 条规则、约 600 个物品码，含金币阈值），加上 6 份内置档位
// （轻度 / 标准 / 严格 × 藏箭矢 / 身上有弓弩不藏箭矢）。内置档位是「类似 PC 端屏蔽」的那一套：藏杂物、低级药水、卷轴与书、
// 投掷药水、劣质装备；标准档起再藏普通档的白装与蓝装，但无形 / 带孔、职业专属、头环、饰品一律留着；严格档把这些放宽到全档位，
// 并藏掉普通档的暗金与绿装。符文、宝石、护身符、珠宝、任务物品、金币、钥匙从不提，因此永远可见。
// 选哪一份：缺省 = Meng3c（开关开着就生效）；<存档>/Settings/dm-lootfilter.txt 里写 profile=<配置名> 可写死
// （也认 auto / off，或你自己放进 Settings/ 的任何 <名字>.fltr —— 原版启动时全部载入，名字 15 字节以内即可）。
// 宿主做的事：挂存档时把所有规则文件写进 Settings/（原版只在启动时载入规则文件，所以要赶在那之前）；之后主线程每半秒看一眼
// 「现在该用哪一份」（配置 / 难度 / 开关 / 身上有没有弓弩），和过滤器对象里的「当前配置名」不一样就改过去。
// 当前配置名 = 过滤器对象 main+0x2d58520 的 +0x20：原版自己的字符串（+0 字符指针、+8 长度、+0x10 容量，最高位是标志；15 字以内存在对象自带的缓冲里）。
// 判定函数每次都按这个名字去已载入的配置里查（0x37d5fc），所以改名字即时生效；我们的名字都不超过 15 个字符，只在现有容量够时原地改写。
// lootfilter.json 不碰：实测原版只在启动时读它一次，进局时用的是内存里那份「角色 → 配置」，改文件不管用；进局时原版按它把名字设回去，下一次巡检再改过来。
// 身上装着弓 / 弩（含副手那套）时箭矢弩矢不藏，局中换上 / 卸下弓半秒内跟着变。
// 开关：「自定义」设置 loot_filter（缺省开 = 用 Meng3c；关 = 全显示；dm-lootfilter.txt 写了 profile 时以文件为准）。
// 测试强制：DM_LOOTFILTER=off / lite / std / strict / meng，DM_LOOTFILTER_PROFILE=<配置名>。
//
// Loot filter (uses the game's built-in loot filter rather than building our own): the default is the imported "Meng3c" filter
// (active on every difficulty); it can be changed to the difficulty tiers (profile=auto) or pinned to one tier (lite / std / strict)
// in <save>/Settings/dm-lootfilter.txt.
// The rule bodies are no longer formatted here: seven ready-made JSON profiles generated by fltr.py are embedded in
// dm_lootfilter_data.h and written into Settings/ when the save is mounted. Seven = the author's imported Meng3c filter + the six
// built-in tiers (lite / standard / strict × hide arrows / keep them while a bow is equipped). The tiers mirror a PC-style hide filter:
// junk potions, low healing/mana potions, scrolls and tomes, throwing potions, low-quality gear; from standard on, normal-tier white and
// magic items are hidden too, while ethereal/socketed, class-specific, circlet and accessory items are always kept; strict widens that to
// all tiers and also hides normal-tier unique and set items. Runes, gems, charms, jewels, quest items, gold and keys are never mentioned,
// so they are always visible.
// Which one: Meng3c by default; a profile written in <save>/Settings/dm-lootfilter.txt (profile=<name>, also accepts auto / off, or any
// <name>.fltr you copy into Settings/ yourself — the game loads every rule file at startup, names must fit 15 bytes).
// What the host does: on save mount, write all rule files into Settings/ (the game only loads rule files at startup, so it must happen
// before that); after that the main thread looks every half second at "which one should be in use now" (config, difficulty, switch, bow or
// crossbow equipped) and changes the filter object's "current profile name" if it differs.
// Current profile name = +0x20 of the filter object main+0x2d58520: the game's own string (+0 char pointer, +8 length, +0x10 capacity, top
// bit is a flag; up to 15 chars live in the object's inline buffer). The check looks the name up among the loaded profiles every time
// (0x37d5fc), so changing the name takes effect at once; our names are all at most 12 characters, and we only rewrite in place when the
// existing capacity is enough. lootfilter.json is not touched. With a bow / crossbow equipped (including the off-hand set) arrows and
// bolts are not hidden; equipping / removing a bow mid-game is followed within half a second.
// Switch: "Custom" setting loot_filter (default on = Meng3c; off = show everything; a pinned profile wins over the switch).
// Test override: DM_LOOTFILTER=off / lite / std / strict / meng, DM_LOOTFILTER_PROFILE=<name>.
